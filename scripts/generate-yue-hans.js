import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import * as OpenCCModule from 'opencc-js'
import messagesYueHant from '../locales/yue-Hant.source.mjs'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const projectRoot = resolve(__dirname, '..')
const outputPath = resolve(projectRoot, 'locales/yue-Hans.generated.ts')

typecheckInput(messagesYueHant)

const openCCModuleRecord = OpenCCModule
const resolvedOpenCC = openCCModuleRecord.default ?? OpenCCModule
const converterFactory = typeof resolvedOpenCC.Converter === 'function'
  ? resolvedOpenCC.Converter
  : null

if (!converterFactory) {
  throw new Error('OpenCC Converter unavailable')
}

const toSimplified = converterFactory({ from: 'hk', to: 'cn' })

const convertValue = (value) => {
  if (typeof value === 'string') {
    return toSimplified(value)
  }

  if (Array.isArray(value)) {
    return value.map((item) => convertValue(item))
  }

  if (value && typeof value === 'object') {
    const out = {}
    for (const [key, nestedValue] of Object.entries(value)) {
      out[key] = convertValue(nestedValue)
    }
    return out
  }

  return value
}

const applyStringOverrides = (messages, overrides) => {
  for (const [path, value] of Object.entries(overrides)) {
    const segments = path.split('.')
    let cursor = messages

    for (let i = 0; i < segments.length - 1; i += 1) {
      const segment = segments[i]
      const nested = cursor?.[segment]

      if (!nested || typeof nested !== 'object' || Array.isArray(nested)) {
        cursor = null
        break
      }

      cursor = nested
    }

    const lastSegment = segments[segments.length - 1]
    if (cursor && lastSegment) {
      cursor[lastSegment] = value
    }
  }

  return messages
}

function typecheckInput(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error('messagesYueHant must be a plain object')
  }
}

const yueHansOverrides = {}
const generated = applyStringOverrides(convertValue(messagesYueHant), yueHansOverrides)

const header = [
  '// Auto-generated by scripts/generate-yue-hans.js',
  '// Do not edit this file directly.',
  ''
].join('\n')

const body = `const messagesYueHans = ${JSON.stringify(generated, null, 2)}\n\nexport default messagesYueHans\n`
const nextContent = `${header}${body}`

let prevContent = ''
try {
  prevContent = await readFile(outputPath, 'utf8')
} catch {
  // ignore if file does not exist
}

if (prevContent === nextContent) {
  console.log('yue-Hans is already up to date')
} else {
  await writeFile(outputPath, nextContent, 'utf8')
  console.log('Generated locales/yue-Hans.generated.ts')
}
