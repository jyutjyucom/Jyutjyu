#!/usr/bin/env node

import {
  DEFAULT_TTS_VOICE_ID,
  DEFAULT_TTS_VOICE_VERSION,
  TTS_CATALOG_PATH,
  buildCatalog,
  writeJsonFile,
} from "./tts-shared.mjs";

const voiceId = process.env.TTS_VOICE_ID || DEFAULT_TTS_VOICE_ID;
const voiceVersion = process.env.TTS_VOICE_VERSION || DEFAULT_TTS_VOICE_VERSION;
const baseUrl =
  process.env.TTS_BASE_URL ||
  process.env.NUXT_PUBLIC_TTS_BASE_URL ||
  "/tts/audio";

const catalog = await buildCatalog({ voiceId, voiceVersion });

await writeJsonFile(TTS_CATALOG_PATH, catalog);

console.log(
  `Extracted ${catalog.itemCount} supported pronunciations from ${catalog.source} into ${TTS_CATALOG_PATH}`,
);
console.log(
  `Runtime manifest is generated by sync after audio exists (expected base URL ${baseUrl}).`,
);
